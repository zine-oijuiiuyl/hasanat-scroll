#!/usr/bin/env python3
"""Builds src/learn-data.js: the units and lessons of the learning path.

Only the shape of the path is bundled (which ayat or hadiths make up each lesson).
The texts themselves are downloaded by the app one surah or hadith at a time, from
fawazahmed0/quran-api and fawazahmed0/hadith-api (public domain), and cached on the phone.

Run from mobile/: python3 scripts/build-learn.py
"""
import json, os, re, urllib.request

RAW = "https://raw.githubusercontent.com/fawazahmed0"
CACHE = os.environ.get("LEARN_CACHE", "/tmp/claude-0/learn")
os.makedirs(CACHE, exist_ok=True)

def get(name, url):
    p = os.path.join(CACHE, name)
    if not os.path.exists(p):
        with urllib.request.urlopen(url) as r, open(p, "wb") as f:
            f.write(r.read())
    return json.load(open(p))

PART = 10   # lessons per unit; long surahs and books are split into parts

# ---------- Qur'an ----------
info = get("qinfo.json", RAW + "/quran-api/1/info.json")
ar = get("qar.json", RAW + "/quran-api/1/editions/ara-quranuthmanihaf.min.json")["quran"]
words = {}
for v in ar:
    words.setdefault(v["chapter"], []).append(len(v["text"].split()))
names = [[c["arabicname"], c["name"], c["englishname"]] for c in info["chapters"]]

def quran_lessons(s):
    out, cur, n = [], [], 0
    for i, w in enumerate(words[s], 1):
        if cur and (n + w > 28 or len(cur) >= 5):
            out.append([cur[0], cur[-1]]); cur, n = [], 0
        cur.append(i); n += w
    if cur:
        out.append([cur[0], cur[-1]])
    return out

# The usual memorising order: al-Fatiha, then from an-Nas back to al-Baqarah.
q_units = []
for s in [1] + list(range(114, 1, -1)):
    ls = quran_lessons(s)
    for p in range(0, len(ls), PART):
        q_units.append([s, p // PART + 1 if len(ls) > PART else 0, ls[p:p + PART]])

# ---------- Hadith ----------
# Only the two Sahih collections and the two well-known forties, so every hadith on the path is authentic.
COLS = ["nawawi", "qudsi", "bukhari", "muslim"]
hinfo = get("hinfo.json", RAW + "/hadith-api/1/info.json")
h_units, h_meta, skip = [], {}, {}
for c in COLS:
    eng = {h["hadithnumber"]: h["text"] for h in get("h-eng-%s.json" % c, RAW + "/hadith-api/1/editions/eng-%s.min.json" % c)["hadiths"]}
    ara = {h["hadithnumber"]: h["text"] for h in get("h-ara-%s.json" % c, RAW + "/hadith-api/1/editions/ara-%s.min.json" % c)["hadiths"]}
    meta = hinfo[c]["metadata"]
    h_meta[c] = {"name": meta["name"], "sections": {k: v for k, v in meta["sections"].items() if v}}
    bad = []
    for sec, d in sorted(meta["section_details"].items(), key=lambda x: int(x[0])):
        a, b = d["hadithnumber_first"], d["hadithnumber_last"]
        if not a or not meta["sections"].get(sec):
            continue
        lessons, cur, n = [], [], 0
        for num in range(int(a), int(b) + 1):
            e = (eng.get(num) or "").strip()
            if not e or not (ara.get(num) or "").strip():
                bad.append(num); continue
            L = len(e)
            if cur and (n + L > 900 or len(cur) >= 3):
                lessons.append([cur[0], cur[-1]]); cur, n = [], 0
            cur.append(num); n += L
        if cur:
            lessons.append([cur[0], cur[-1]])
        for p in range(0, len(lessons), PART):
            h_units.append([c, int(sec), p // PART + 1 if len(lessons) > PART else 0, lessons[p:p + PART]])
    skip[c] = bad

out = "// Generated by scripts/build-learn.py. Do not edit by hand.\n"
out += "// Lesson ranges are [first, last]: ayat for the Qur'an, hadith numbers for hadith (minus HSKIP).\n"
out += "export const QNAMES = " + json.dumps(names, ensure_ascii=False, separators=(",", ":")) + ";\n"
out += "export const QUNITS = " + json.dumps(q_units, separators=(",", ":")) + ";\n"
out += "export const HMETA = " + json.dumps(h_meta, ensure_ascii=False, separators=(",", ":")) + ";\n"
out += "export const HUNITS = " + json.dumps(h_units, separators=(",", ":")) + ";\n"
out += "export const HSKIP = " + json.dumps(skip, separators=(",", ":")) + ";\n"
open(os.path.join(os.path.dirname(__file__), "..", "src", "learn-data.js"), "w").write(out)
print("quran units", len(q_units), "lessons", sum(len(u[2]) for u in q_units))
print("hadith units", len(h_units), "lessons", sum(len(u[3]) for u in h_units), "skipped", {k: len(v) for k, v in skip.items()})
print("bytes", len(out.encode()))
