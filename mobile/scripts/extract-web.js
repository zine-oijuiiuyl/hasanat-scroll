// Copies the content, translations, rules, buddy drawing and prayer maths out of the web app
// (../index.html) into src/web-data.js, so both apps share one source of truth.
// Run after editing index.html: node scripts/extract-web.js
const fs = require("fs");
const path = require("path");

const html = fs.readFileSync(path.join(__dirname, "..", "..", "index.html"), "utf8");
const cut = (from, to) => {
  const a = html.indexOf(from);
  const b = html.indexOf(to, a);
  if (a < 0 || b < 0) throw new Error("Marker not found: " + (a < 0 ? from : to));
  return html.slice(a, b);
};

const parts = [
  cut("// ---------- Content ----------", "// Language in use."),
  cut("const RULES = {", "// ---------- Storage"),
  cut("const PAL = {", "// The buddy that rides along"),
  cut("const PR_NAMES = [", "const hhmm ="),
];

const out = `// Generated by scripts/extract-web.js from ../index.html. Do not edit by hand.
/* eslint-disable */
const esc = s => String(s).replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
const stageName = () => "";

${parts.join("\n")}

export { PAL, PALETTES, LIB, BY_ID, LANGS, T, NEW_T, RULES, isMilestone, threshold, levelFor, levelProgress, STAGES, growthFor, stageFor, stageProgress, BADGES, charSVG, PR_NAMES, PR_METHODS, prayerHours, prayerDay, guessMethod };
`;
fs.writeFileSync(path.join(__dirname, "..", "src", "web-data.js"), out);
console.log("Wrote src/web-data.js (" + out.length + " bytes)");
